"""Pydantic request/response models for the FastAPI layer."""
from __future__ import annotations

import re
from typing import Any, Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator

_SESSION_ID_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


class QueryRequest(BaseModel):
    model_config = ConfigDict(json_schema_extra={
        "example": {"question": "What is the reimbursement policy?", "department": "Finance"}
    })

    question: str = Field(..., min_length=3, description="Natural-language question.")
    department: Optional[str] = Field(
        None, description="Department name or slug (partial names such as 'Sales' work). Omit it to let the server detect a department "
                     "from the wording (\"the Finance department's ...\"); send 'all' to search every department with no detection."
    )
    document_type: Optional[str] = Field(None, description="e.g. Policy, SOP, Guidelines, Agreement.")
    filename: Optional[str] = Field(None, description="Restrict to one source file (exact name).")
    top_k: Optional[int] = Field(None, ge=1, le=20, description="Override the configured TOP_K.")
    session_id: Optional[str] = Field(
        None, max_length=64,
        description="Opaque conversation id (generated by the frontend, stored in sessionStorage) used to "
                    "retrieve recent chat history for follow-up questions. Omit for a one-off, context-free query.",
    )

    @field_validator("question")
    @classmethod
    def _strip(cls, value: str) -> str:
        value = value.strip()
        if len(value) < 3:
            raise ValueError("question must contain at least 3 characters")
        return value

    @field_validator("department", "document_type", "filename")
    @classmethod
    def _blank_to_none(cls, value: Optional[str]) -> Optional[str]:
        if value is None:
            return None
        value = value.strip()
        return value or None

    @field_validator("session_id")
    @classmethod
    def _valid_session_id(cls, value: Optional[str]) -> Optional[str]:
        if value is None:
            return None
        value = value.strip()
        if not value:
            return None
        if not _SESSION_ID_RE.match(value):
            raise ValueError("session_id must be 1-64 characters of letters, digits, '_' or '-'")
        return value


class SourceRef(BaseModel):
    citation_id: int
    document_id: str
    document: str = Field(..., description="Relative source path, e.g. Finance/09_Expense_and_Reimbursement_Policy.docx")
    title: Optional[str] = None
    doc_code: Optional[str] = None
    department: str
    department_slug: str
    file_type: Optional[str] = None
    page: Optional[int] = None
    section: Optional[str] = None
    sheet: Optional[str] = None
    version: Optional[str] = None
    status: Optional[str] = None
    classification: Optional[str] = None
    score: Optional[float] = None
    excerpt: str = ""
    used_in_answer: bool = True


class ProductCard(BaseModel):
    product_id: int
    name: str
    category: str
    region: str
    city: str
    price_inr: float
    competitor_price_inr: Optional[float] = None
    competitor_price_is_illustrative: Optional[bool] = None
    image: str = Field(..., description="Path relative to the frontend root, e.g. images/Bihar/51_x.jpg")
    url: str = Field(..., description="In-page product route, e.g. #product-51")


class LiveCompetitorPrice(BaseModel):
    competitor_name: str
    competitor_product_name: str
    competitor_price_inr: int
    source_url: str
    price_checked_at: str
    comparison_type: str
    price_verified: bool
    verification_status: str
    source_name: Optional[str] = None
    evidence: Optional[str] = Field(None, description="Page text around the price, as fetched - shown as evidence.")


class LivePriceStatus(BaseModel):
    """Outcome of a live competitor-price lookup, so the UI can show verified vs not verified."""
    requested: bool = True
    verified: bool = False
    product_id: Optional[int] = None
    product_name: Optional[str] = None
    message: Optional[str] = None
    checked_at: Optional[str] = None


class Timings(BaseModel):
    retrieval_ms: int = 0
    generation_ms: int = 0
    total_ms: int = 0


class QueryResponse(BaseModel):
    answer: str
    products: list[ProductCard] = Field(default_factory=list)
    live_competitor_prices: list[LiveCompetitorPrice] = Field(default_factory=list)
    live_price_status: Optional[LivePriceStatus] = None
    sources: list[SourceRef] = Field(default_factory=list)
    grounded: bool = Field(True, description="False when nothing relevant was retrieved and the LLM was not called.")
    retrieved_count: int = 0
    applied_filters: dict[str, Any] = Field(default_factory=dict)
    model: Optional[str] = None
    timings: Timings = Field(default_factory=Timings)
    off_peak: bool = True
    notice: Optional[str] = None
    session_id: Optional[str] = Field(
        None, description="Echoes the conversation id this turn was stored under; pass it back on the next "
                    "request in this conversation so follow-ups ('it', 'this product') can be resolved.",
    )


class ComponentStatus(BaseModel):
    status: str  # ok | error | not_configured | degraded
    detail: Optional[str] = None


class HealthResponse(BaseModel):
    status: str
    version: str
    components: dict[str, ComponentStatus]
    off_peak: bool
    off_peak_enabled: bool
    embedding: str
    llm_model: str


class DepartmentInfo(BaseModel):
    slug: str
    name: str
    document_count: int
    chunk_count: Optional[int] = None


class DocumentInfo(BaseModel):
    document_id: str
    title: Optional[str] = None
    doc_code: Optional[str] = None
    source_filename: str
    source_path: str
    department: str
    department_slug: str
    file_type: str
    document_type: Optional[str] = None
    version: Optional[str] = None
    status: Optional[str] = None
    classification: Optional[str] = None
    page_count: Optional[int] = None
    chunk_count: Optional[int] = None
    indexed: bool = False
    processing_timestamp: Optional[str] = None
    parser: Optional[str] = None


class StatsResponse(BaseModel):
    documents_total: int
    documents_indexed: int
    chunks_total: Optional[int] = None
    by_department: dict[str, int]
    by_file_type: dict[str, int]
    parsing: dict[str, int]
    embedding: str
    llm_model: str
    source: str = Field(..., description="'database' when live registry data is used, else 'manifest'.")


class SourceDetail(DocumentInfo):
    header_metadata: dict[str, Any] = Field(default_factory=dict)
    validation: dict[str, Any] = Field(default_factory=dict)
    related_documents: list[str] = Field(default_factory=list)
    markdown: Optional[str] = None
    markdown_truncated: bool = False


class OrderItem(BaseModel):
    product_id: int
    quantity: int = Field(..., ge=1)
    unit_price: float
    subtotal: float


class OrderRequest(BaseModel):
    order_id: str
    customer_id: str
    total_amount: float
    shipping_city: str
    shipping_state: str
    item: OrderItem


class IngestRequest(BaseModel):
    department: Optional[str] = None
    force: bool = False


class IngestJob(BaseModel):
    job_id: str
    status: str  # queued | running | done | failed
    detail: Optional[str] = None
    summary: dict[str, Any] = Field(default_factory=dict)


class ErrorBody(BaseModel):
    code: str
    message: str
    hint: Optional[str] = None


class ErrorResponse(BaseModel):
    error: ErrorBody
