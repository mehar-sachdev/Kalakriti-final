"""Database-backed chat memory: one row per conversation, one row per message.

This is the persistence half of "conversation context" - a session id is
generated by the frontend (kept in sessionStorage, not the messages
themselves), and every turn's user question + assistant answer is stored
here so a follow-up question ("What is its price?") can be resolved by
looking at what was actually discussed, even across a page reload or a
different device. Deliberately NOT a new/unrelated database: same Supabase
Postgres connection and schema as the RAG chunk/document tables
(backend/database/registry.py), just two more tables.
"""
from __future__ import annotations

import json
import logging
from typing import Any

from sqlalchemy import text
from sqlalchemy.engine import Engine
from sqlalchemy.exc import SQLAlchemyError

from backend.config import Settings
from backend.database.connection import explain_db_error, safe_identifier

logger = logging.getLogger(__name__)


class ConversationStore:
    def __init__(self, engine: Engine, settings: Settings):
        self.engine = engine
        schema = safe_identifier(settings.db_schema)
        self.conversations = f"{schema}.conversations"
        self.messages = f"{schema}.messages"

    def _run(self, sql: str, params: dict[str, Any] | None = None, *, fetch: bool = False):
        try:
            with self.engine.begin() as conn:
                result = conn.execute(text(sql), params or {})
                return [dict(r._mapping) for r in result] if fetch else None
        except SQLAlchemyError as exc:
            raise explain_db_error(exc) from exc

    # ---------------------------------------------------------------- writes
    def ensure_session(self, session_id: str) -> None:
        self._run(
            f"""insert into {self.conversations} (session_id) values (:id)
                on conflict (session_id) do update set last_active_at = now()""",
            {"id": session_id},
        )

    def add_message(
        self, session_id: str, role: str, content: str, *,
        product_ids: list[int] | None = None, sources: list[dict] | None = None,
    ) -> None:
        self.ensure_session(session_id)
        self._run(
            f"""insert into {self.messages} (session_id, role, content, product_ids, sources)
                values (:session_id, :role, :content, :product_ids, cast(:sources as jsonb))""",
            {
                "session_id": session_id, "role": role, "content": content,
                "product_ids": product_ids or [],
                "sources": json.dumps(sources, ensure_ascii=False) if sources is not None else None,
            },
        )
        if product_ids:
            self._run(
                f"update {self.conversations} set last_active_at = now(), last_product_ids = :p where session_id = :id",
                {"id": session_id, "p": product_ids},
            )
        else:
            self._run(
                f"update {self.conversations} set last_active_at = now() where session_id = :id",
                {"id": session_id},
            )

    # ---------------------------------------------------------------- reads
    def recent_messages(self, session_id: str, limit: int = 10) -> list[dict[str, Any]]:
        """Most recent `limit` messages, returned oldest-first (reading order)."""
        rows = self._run(
            f"""select role, content, product_ids, sources, created_at from
                (select * from {self.messages} where session_id = :id order by created_at desc, id desc limit :n) recent
                order by created_at asc, id asc""",
            {"id": session_id, "n": limit}, fetch=True,
        )
        return rows or []

    def last_product_ids(self, session_id: str) -> list[int]:
        rows = self._run(
            f"select last_product_ids from {self.conversations} where session_id = :id", {"id": session_id}, fetch=True,
        )
        return list(rows[0]["last_product_ids"]) if rows and rows[0]["last_product_ids"] else []

    def session_exists(self, session_id: str) -> bool:
        rows = self._run(
            f"select 1 from {self.conversations} where session_id = :id", {"id": session_id}, fetch=True,
        )
        return bool(rows)
